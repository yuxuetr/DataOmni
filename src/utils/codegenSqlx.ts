import {
  logicalType,
  NameScope,
  noteLines,
  pascalCase,
  snakeCase,
  type CodegenDialect,
  type CodegenNote,
  type CodegenSchema,
  type GeneratedCode
} from './codegenModel';
import { escapeRustKeyword, RUST_KEYWORDS, rustString, rustType, SQLX_TYPES } from './codegenRust';

/**
 * sqlx：一个 `models.rs`，每张表一个 `#[derive(sqlx::FromRow)]` 结构体，没有关系（sqlx 本来就没有）。
 * 不要求主键：`FromRow` 只管把一行的列放进字段。sqlx 0.7 起不再支持 SQL Server，Oracle 从来没有
 */
export type SqlxDialect = Extract<CodegenDialect, 'postgresql' | 'mysql' | 'sqlite'>;

export function isSqlxDialect(dialect: CodegenDialect): dialect is SqlxDialect {
  return dialect === 'postgresql' || dialect === 'mysql' || dialect === 'sqlite';
}

export function generateSqlx(schema: CodegenSchema & { dialect: SqlxDialect }, source: string): GeneratedCode {
  const notes: CodegenNote[] = [];
  const structScope = new NameScope(new Set(['Self']), (name) => `${name}Row`);
  const multiSchema = new Set(schema.tables.map((table) => table.schema)).size > 1;

  const structs = schema.tables.map((table) => {
    const plain = pascalCase(table.name);
    const name = structScope.claim(
      multiSchema && table.schema && schema.tables.some((other) => other !== table && pascalCase(other.name) === plain)
        ? pascalCase(`${table.schema}_${table.name}`)
        : plain
    );
    const fields = new NameScope(RUST_KEYWORDS, escapeRustKeyword);
    const lines = [
      `/// \`${table.key}\``,
      '#[derive(Debug, Clone, sqlx::FromRow)]',
      `pub struct ${name} {`
    ];
    for (const column of table.columns) {
      const field = fields.claim(snakeCase(column.name));
      const mapped = rustType(logicalType(column.dataType, schema.dialect), schema.dialect, SQLX_TYPES);
      if (!mapped) notes.push({ kind: 'unknown-type', table: table.key, column: column.name, dataType: column.dataType });
      if (field !== column.name) lines.push(`    #[sqlx(rename = ${rustString(column.name)})]`);
      const type = mapped ?? 'String';
      lines.push(`    pub ${field}: ${column.nullable ? `Option<${type}>` : type},`);
    }
    lines.push('}');
    return lines.join('\n');
  });

  const header = [
    `//! Generated by DataOmni from ${source}.`,
    '//! Needs sqlx with the `chrono`, `uuid`, `rust_decimal` and `json` features for the types used below.',
    ...noteLines(notes).map((line) => `//! - ${line}`)
  ].join('\n');
  return { files: [{ path: 'models.rs', contents: `${header}\n\n${structs.join('\n\n')}\n` }], notes };
}
