import {
  camelCase,
  logicalType,
  NameScope,
  noteLines,
  pascalCase,
  planRelations,
  type CodegenColumn,
  type CodegenDialect,
  type CodegenNote,
  type CodegenSchema,
  type CodegenTable,
  type GeneratedCode,
  type GeneratedFile,
  type LogicalType,
  type RelationPlan
} from './codegenModel';
import { entityFileName, TS_RESERVED_PROPERTIES, tsObject, tsString, tsType } from './codegenTs';

/**
 * MikroORM 实体（装饰器写法）：一张表一个 `*.entity.ts`，外加 `index.ts`。Oracle 不在 MikroORM 支持的库里。
 *
 * 与 TypeORM 的不同：MikroORM 里一列只能映射一个属性，所以外键列**只**出现在关系上
 * （外键列也是主键时，关系标 `primary: true`），不再另写成普通属性。
 * 列的原文写进 `columnType`（MikroORM 收任意字符串），`type` 只管读出来的 JS 值，必须写：
 * `string | null` 在装饰器元数据里只剩 Object，发现实体时报「Please provide either 'type' or 'entity'」
 */
export type MikroormDialect = Exclude<CodegenDialect, 'oracle'>;

export function isMikroormDialect(dialect: CodegenDialect): dialect is MikroormDialect {
  return dialect !== 'oracle';
}

interface Entity {
  table: CodegenTable;
  className: string;
  fileName: string;
  propertyOf: Map<string, string>;
  /** 被关系接管的外键列：不再写成普通属性 */
  relationColumns: Set<string>;
  scope: NameScope;
  members: string[][];
  imports: Set<string>;
  typeImports: Set<string>;
  entityImports: Set<string>;
}

export function generateMikroorm(schema: CodegenSchema & { dialect: MikroormDialect }, source: string): GeneratedCode {
  const notes: CodegenNote[] = [];
  const classScope = new NameScope();
  const fileScope = new NameScope();
  const multiSchema = new Set(schema.tables.map((table) => table.schema)).size > 1;

  const entities: Entity[] = [];
  for (const table of schema.tables) {
    if (table.primaryKey.length === 0) {
      notes.push({ kind: 'skipped-table', table: table.key, reason: 'no-primary-key' });
      continue;
    }
    const plain = pascalCase(table.name);
    const className = classScope.claim(
      multiSchema && table.schema && schema.tables.some((other) => other !== table && pascalCase(other.name) === plain)
        ? pascalCase(`${table.schema}_${table.name}`)
        : plain
    );
    entities.push({
      table,
      className,
      fileName: entityFileName(table.name, fileScope),
      propertyOf: new Map(),
      relationColumns: new Set(),
      scope: new NameScope(TS_RESERVED_PROPERTIES),
      members: [],
      imports: new Set(['Entity']),
      typeImports: new Set(),
      entityImports: new Set()
    });
  }

  const byKey = new Map(entities.map((entity) => [entity.table.key, entity]));
  const { relations, dangling } = planRelations(schema);
  for (const item of dangling) {
    notes.push({ kind: 'dangling-foreign-key', table: item.table.key, constraint: item.foreignKey.name, referencedTable: item.foreignKey.referencedTable });
  }

  // 先定哪些外键由关系接管：一列只能属于一条关系，后来的那条只好不生成
  const owned: RelationPlan[] = [];
  for (const relation of relations) {
    const source = byKey.get(relation.source.key);
    const target = byKey.get(relation.target.key);
    if (!source || !target) {
      notes.push({ kind: 'skipped-relation', table: relation.source.key, constraint: relation.foreignKey.name, reason: 'skipped-table' });
      continue;
    }
    if (relation.foreignKey.columns.some((column) => source.relationColumns.has(column))) {
      notes.push({ kind: 'skipped-relation', table: relation.source.key, constraint: relation.foreignKey.name, reason: 'shared-column' });
      continue;
    }
    relation.foreignKey.columns.forEach((column) => source.relationColumns.add(column));
    owned.push(relation);
  }

  // 普通属性先占名字，关系的名字在后面分配时避开它们
  for (const entity of entities) {
    for (const column of entity.table.columns) {
      if (entity.relationColumns.has(column.name)) continue;
      const property = entity.scope.claim(camelCase(column.name));
      entity.propertyOf.set(column.name, property);
      entity.members.push(scalarMember(entity, column, property, schema.dialect, notes));
    }
  }
  const forwardNames = new Map<RelationPlan, string>();
  for (const relation of owned) {
    const source = byKey.get(relation.source.key);
    if (source) forwardNames.set(relation, source.scope.claim(camelCase(relation.forwardBase)));
  }
  for (const relation of owned) {
    const source = byKey.get(relation.source.key);
    const target = byKey.get(relation.target.key);
    const forward = forwardNames.get(relation);
    if (source && target && forward) addRelation(relation, source, target, forward);
  }

  const header = `// Generated by DataOmni from ${source}.`;
  const files: GeneratedFile[] = entities.map((entity) => ({
    path: entity.fileName,
    contents: renderEntity(entity, schema.dialect, byKey, header)
  }));
  files.push({ path: 'index.ts', contents: renderIndex(entities, notes, header) });
  return { files, notes };
}

/** `type` 管读出来的 JS 值；与 `tsType` 一一对应 */
function mikroType(logical: LogicalType): string {
  switch (logical.kind) {
    case 'int':
      return logical.bytes === 8 ? 'bigint' : 'integer';
    case 'decimal':
      return 'decimal';
    case 'float':
      return 'double';
    case 'bool':
      return 'boolean';
    case 'text':
      return 'text';
    case 'uuid':
      return 'uuid';
    case 'json':
      return 'json';
    case 'bytes':
      return 'blob';
    case 'date':
      return 'date';
    case 'time':
      return 'time';
    case 'timestamp':
      return 'datetime';
    case 'string':
    case 'unknown':
      return 'string';
  }
}

function scalarMember(
  entity: Entity,
  column: CodegenColumn,
  property: string,
  dialect: MikroormDialect,
  notes: CodegenNote[]
): string[] {
  const table = entity.table;
  const logical = logicalType(column.dataType, dialect);
  if (logical.kind === 'unknown') {
    notes.push({ kind: 'unknown-type', table: table.key, column: column.name, dataType: column.dataType });
  }
  const isPrimary = table.primaryKey.includes(column.name);
  const options: Array<[string, string]> = [];
  if (property !== column.name) options.push(['fieldName', tsString(column.name)]);
  options.push(['type', tsString(mikroType(logical))]);
  if (column.dataType.trim()) options.push(['columnType', tsString(column.dataType.trim())]);
  if (isPrimary && logical.kind === 'int') options.push(['autoincrement', String(column.autoIncrement && table.primaryKey.length === 1)]);
  const nullable = column.nullable && !isPrimary;
  if (nullable) options.push(['nullable', 'true']);
  if (table.unique.some((columns) => columns.length === 1 && columns[0] === column.name)) options.push(['unique', 'true']);
  if (column.defaultValue != null) options.push(['defaultRaw', tsString(column.defaultValue)]);

  const decorator = isPrimary ? 'PrimaryKey' : 'Property';
  entity.imports.add(decorator);
  const lines = column.computed ? ['/** Computed by the database; do not set it. */'] : [];
  lines.push(`@${decorator}(${tsObject(options)})`, `${property}!: ${tsType(logical)}${nullable ? ' | null' : ''};`);
  return lines;
}

function addRelation(relation: RelationPlan, source: Entity, target: Entity, forward: string): void {
  const back = target.scope.claim(camelCase(relation.backBase));
  const columns = relation.foreignKey.columns;
  const nullable = columns.some((name) => relation.source.columns.find((column) => column.name === name)?.nullable);
  const primary = columns.every((name) => relation.source.primaryKey.includes(name));
  const options: Array<[string, string]> = [['entity', `() => ${target.className}`]];
  if (relation.oneToOne) options.push(['owner', 'true'], ['inversedBy', tsString(back)]);
  else options.push(['inversedBy', tsString(back)]);
  if (columns.length === 1) options.push(['fieldName', tsString(columns[0])]);
  else options.push(['joinColumns', `[${columns.map(tsString).join(', ')}]`]);
  const referenced = relation.foreignKey.referencedColumns;
  const referencesPrimary = referenced.length === relation.target.primaryKey.length
    && referenced.every((name, index) => relation.target.primaryKey[index] === name);
  if (!referencesPrimary) options.push(['referencedColumnNames', `[${referenced.map(tsString).join(', ')}]`]);
  if (primary) options.push(['primary', 'true']);
  if (nullable && !primary) options.push(['nullable', 'true']);
  if (relation.foreignKey.onDelete) options.push(['deleteRule', tsString(relation.foreignKey.onDelete)]);

  const kind = relation.oneToOne ? 'OneToOne' : 'ManyToOne';
  source.imports.add(kind);
  source.typeImports.add('Rel');
  source.entityImports.add(target.table.key);
  source.members.push([
    `@${kind}(${tsObject(options)})`,
    `${forward}!: Rel<${target.className}>${nullable && !primary ? ' | null' : ''};`
  ]);

  target.entityImports.add(source.table.key);
  if (relation.oneToOne) {
    target.imports.add('OneToOne');
    target.typeImports.add('Rel');
    target.members.push([
      `@OneToOne(${tsObject([['entity', `() => ${source.className}`], ['mappedBy', tsString(forward)], ['nullable', 'true']])})`,
      `${back}?: Rel<${source.className}> | null;`
    ]);
  } else {
    target.imports.add('OneToMany').add('Collection');
    target.members.push([
      `@OneToMany(${tsObject([['entity', `() => ${source.className}`], ['mappedBy', tsString(forward)]])})`,
      `${back} = new Collection<${source.className}>(this);`
    ]);
  }
}

function renderEntity(entity: Entity, dialect: MikroormDialect, byKey: Map<string, Entity>, header: string): string {
  const table = entity.table;
  const composites = table.unique.filter(
    (columns) => columns.length > 1 && columns.every((name) => entity.propertyOf.has(name))
  );
  if (composites.length) entity.imports.add('Unique');
  const lines = [header, `import { ${[...entity.imports].sort().join(', ')} } from '@mikro-orm/core';`];
  if (entity.typeImports.size) lines.push(`import type { ${[...entity.typeImports].sort().join(', ')} } from '@mikro-orm/core';`);
  for (const key of [...entity.entityImports].filter((key) => key !== table.key).sort()) {
    const other = byKey.get(key);
    if (other) lines.push(`import { ${other.className} } from './${other.fileName.replace(/\.ts$/, '')}';`);
  }
  lines.push('');

  const entityOptions: Array<[string, string]> = [['tableName', tsString(table.name)]];
  if (table.schema && dialect !== 'mysql' && dialect !== 'sqlite') entityOptions.push(['schema', tsString(table.schema)]);
  lines.push(`@Entity(${tsObject(entityOptions)})`);
  for (const columns of composites) {
    lines.push(`@Unique({ properties: [${columns.map((name) => tsString(entity.propertyOf.get(name) ?? name)).join(', ')}] })`);
  }
  lines.push(`export class ${entity.className} {`);
  entity.members.forEach((member, index) => {
    if (index > 0) lines.push('');
    lines.push(...member.map((line) => `  ${line}`));
  });
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

function renderIndex(entities: Entity[], notes: CodegenNote[], header: string): string {
  const lines = [header, ...noteLines(notes).map((line) => `// - ${line}`)];
  for (const entity of entities) {
    lines.push(`import { ${entity.className} } from './${entity.fileName.replace(/\.ts$/, '')}';`);
  }
  lines.push('');
  lines.push(`export { ${entities.map((entity) => entity.className).join(', ')} };`);
  lines.push('');
  lines.push('/** Pass to `MikroOrmModule.forRoot({ entities })` or `MikroORM.init({ entities })`. */');
  lines.push(`export const entities = [${entities.map((entity) => entity.className).join(', ')}];`);
  return `${lines.join('\n')}\n`;
}
