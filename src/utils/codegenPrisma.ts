/**
 * `schema.prisma`。Prisma 不支持 Oracle；DuckDB、ClickHouse 不在 `CodegenDialect` 里。
 * 规则照 `prisma db pull` 的产物与 `prisma validate` 的报错定，见 rfcs/codegen.md §6
 */
export type PrismaDialect = Exclude<CodegenDialect, 'oracle'>;

export function isPrismaDialect(dialect: CodegenDialect): dialect is PrismaDialect {
  return dialect !== 'oracle';
}

const PROVIDER: Record<PrismaDialect, string> = {
  postgresql: 'postgresql',
  mysql: 'mysql',
  sqlite: 'sqlite',
  sqlserver: 'sqlserver'
};

/** Prisma 自己的标量类型名，不能拿来当模型名 */
const RESERVED_MODEL_NAMES = new Set([
  'String', 'Boolean', 'Int', 'BigInt', 'Float', 'Decimal', 'DateTime', 'Json', 'Bytes', 'Unsupported',
  'Prisma', 'PrismaClient'
]);

interface PrismaField {
  name: string;
  type: string;
  attributes: string[];
  doc?: string;
}

interface PrismaModel {
  table: CodegenTable;
  name: string;
  fields: PrismaField[];
  /** 列名 → 字段名 */
  fieldOf: Map<string, string>;
  scope: NameScope;
  blockAttributes: string[];
  ignored: boolean;
}

export function generatePrisma(schema: CodegenSchema & { dialect: PrismaDialect }, source: string): GeneratedCode {
  const notes: CodegenNote[] = [];
  const models = buildModels(schema, notes);
  const byKey = new Map(models.map((model) => [model.table.key, model]));
  const { relations, dangling } = planRelations(schema);

  for (const item of dangling) {
    notes.push({
      kind: 'dangling-foreign-key',
      table: item.table.key,
      constraint: item.foreignKey.name,
      referencedTable: item.foreignKey.referencedTable
    });
  }
  for (const relation of relations) {
    addRelation(relation, byKey, notes);
  }

  const schemas = [...new Set(schema.tables.map((table) => table.schema).filter((name): name is string => !!name))];
  const multiSchema = schemas.length > 1 && (schema.dialect === 'postgresql' || schema.dialect === 'sqlserver');
  if (multiSchema) {
    for (const model of models) {
      if (model.table.schema) model.blockAttributes.push(`@@schema(${quote(model.table.schema)})`);
    }
  }

  const header = [
    `// Generated by DataOmni from ${source}.`,
    '// Review before use: relation names and field names are derived from the database.',
    ...noteLines(notes).map((line) => `// - ${line}`)
  ];
  const generator = [
    'generator client {',
    '  provider = "prisma-client-js"',
    ...(multiSchema ? ['  previewFeatures = ["multiSchema"]'] : []),
    '}'
  ];
  const datasource = [
    'datasource db {',
    `  provider = ${quote(PROVIDER[schema.dialect])}`,
    '  url      = env("DATABASE_URL")',
    ...(multiSchema ? [`  schemas  = [${schemas.map(quote).join(', ')}]`] : []),
    '}'
  ];
  const blocks = [header.join('\n'), generator.join('\n'), datasource.join('\n'), ...models.map(renderModel)];
  return { files: [{ path: 'schema.prisma', contents: `${blocks.join('\n\n')}\n` }], notes };
}

function buildModels(schema: CodegenSchema & { dialect: PrismaDialect }, notes: CodegenNote[]): PrismaModel[] {
  const modelScope = new NameScope(RESERVED_MODEL_NAMES, (name) => `${name}Model`);
  const pascalCounts = new Map<string, number>();
  for (const table of schema.tables) {
    const name = pascalCase(table.name);
    pascalCounts.set(name, (pascalCounts.get(name) ?? 0) + 1);
  }

  return schema.tables.map((table) => {
    // 两个 schema 里有同名表：类型名前面带上 schema
    const plain = pascalCase(table.name);
    const name = modelScope.claim(
      (pascalCounts.get(plain) ?? 0) > 1 && table.schema ? pascalCase(`${table.schema}_${table.name}`) : plain
    );
    const scope = new NameScope();
    const fieldOf = new Map<string, string>();
    for (const column of table.columns) {
      fieldOf.set(column.name, scope.claim(camelCase(column.name)));
    }

    const ignored = table.primaryKey.length === 0 && table.unique.length === 0;
    if (ignored) notes.push({ kind: 'ignored-table', table: table.key, reason: 'no-unique-identifier' });

    const fields = table.columns.map((column) => scalarField(column, table, fieldOf, schema.dialect, notes));
    const blockAttributes: string[] = [];
    if (table.primaryKey.length > 1) {
      blockAttributes.push(`@@id([${table.primaryKey.map((columnName) => fieldOf.get(columnName)).join(', ')}])`);
    }
    for (const unique of table.unique.filter((columns) => columns.length > 1)) {
      blockAttributes.push(`@@unique([${unique.map((columnName) => fieldOf.get(columnName)).join(', ')}])`);
    }
    if (name !== table.name) blockAttributes.push(`@@map(${quote(table.name)})`);
    if (ignored) blockAttributes.push('@@ignore');
    return { table, name, fields, fieldOf, scope, blockAttributes, ignored };
  });
}

function scalarField(
  column: CodegenColumn,
  table: CodegenTable,
  fieldOf: Map<string, string>,
  dialect: PrismaDialect,
  notes: CodegenNote[]
): PrismaField {
  const logical = logicalType(column.dataType, dialect);
  const name = fieldOf.get(column.name) ?? column.name;
  const mapped = scalarType(logical, column.dataType, dialect);
  if (mapped.type.startsWith('Unsupported(')) {
    notes.push({ kind: 'unknown-type', table: table.key, column: column.name, dataType: column.dataType });
  }
  const isPrimary = table.primaryKey.includes(column.name);
  const attributes: string[] = [];
  if (isPrimary && table.primaryKey.length === 1) attributes.push('@id');
  if (table.unique.some((columns) => columns.length === 1 && columns[0] === column.name)) attributes.push('@unique');
  if (column.autoIncrement && (mapped.type === 'Int' || mapped.type === 'BigInt')) {
    attributes.push('@default(autoincrement())');
  } else if (column.defaultValue != null && !mapped.type.startsWith('Unsupported(')) {
    attributes.push(`@default(${prismaDefault(column.defaultValue, mapped.type)})`);
  }
  if (name !== column.name) attributes.push(`@map(${quote(column.name)})`);
  if (mapped.native) attributes.push(mapped.native);
  const optional = column.nullable && !isPrimary;
  return {
    name,
    type: `${mapped.type}${optional ? '?' : ''}`,
    attributes,
    doc: column.computed ? 'Computed by the database; do not write it.' : undefined
  };
}

/** 逻辑类型 → Prisma 标量与 `@db.*` 原生类型。只写有把握的原生类型：写错了 `prisma validate` 不过 */
function scalarType(logical: LogicalType, raw: string, dialect: PrismaDialect): { type: string; native?: string } {
  const token = columnTypeToken(raw.toLowerCase().replace(/^character varying/, 'varchar').replace(/^double precision/, 'double'));
  const precision = (/\((\d+)\)/.exec(raw) ?? [])[1];
  switch (logical.kind) {
    case 'int': {
      const type = logical.bytes === 8 || (logical.unsigned && logical.bytes === 4 && dialect !== 'mysql') ? 'BigInt' : 'Int';
      if (dialect === 'mysql') {
        const unsigned = logical.unsigned ? 'Unsigned' : '';
        const native = token === 'mediumint' ? 'MediumInt'
          : logical.bytes === 1 ? 'TinyInt'
            : logical.bytes === 2 ? 'SmallInt'
              : logical.bytes === 4 ? 'Int'
                : 'BigInt';
        // 有符号的 int / bigint 就是 Prisma 的默认映射，不写
        const isDefault = !logical.unsigned && (native === 'Int' || native === 'BigInt');
        return { type, native: isDefault ? undefined : `@db.${unsigned}${native}` };
      }
      if (dialect === 'postgresql' && logical.bytes === 2) return { type, native: '@db.SmallInt' };
      if (dialect === 'sqlserver' && logical.bytes === 1) return { type, native: '@db.TinyInt' };
      if (dialect === 'sqlserver' && logical.bytes === 2) return { type, native: '@db.SmallInt' };
      return { type };
    }
    case 'decimal': {
      if (dialect === 'sqlserver' && token === 'money') return { type: 'Decimal', native: '@db.Money' };
      if (dialect === 'sqlserver' && token === 'smallmoney') return { type: 'Decimal', native: '@db.SmallMoney' };
      if (dialect === 'postgresql' && token === 'money') return { type: 'Decimal', native: '@db.Money' };
      if (dialect !== 'sqlite' && logical.precision != null) {
        return { type: 'Decimal', native: `@db.Decimal(${logical.precision}, ${logical.scale ?? 0})` };
      }
      return { type: 'Decimal' };
    }
    case 'float':
      if (logical.bytes === 4) {
        if (dialect === 'postgresql' || dialect === 'sqlserver') return { type: 'Float', native: '@db.Real' };
        if (dialect === 'mysql') return { type: 'Float', native: '@db.Float' };
      }
      return { type: 'Float' };
    case 'bool':
      if (dialect === 'mysql' && token === 'bit') return { type: 'Boolean', native: '@db.Bit(1)' };
      return { type: 'Boolean' };
    case 'string':
      return { type: 'String', native: stringNative(logical, dialect) };
    case 'text':
      if (dialect === 'mysql') {
        const native = { text: 'Text', tinytext: 'TinyText', mediumtext: 'MediumText', longtext: 'LongText' }[token];
        return { type: 'String', native: native ? `@db.${native}` : undefined };
      }
      if (dialect === 'sqlserver') {
        if (token === 'ntext') return { type: 'String', native: '@db.NText' };
        if (token === 'text') return { type: 'String', native: '@db.Text' };
      }
      if (dialect === 'postgresql' && token === 'citext') return { type: 'String', native: '@db.Citext' };
      if (dialect === 'postgresql' && token === 'xml') return { type: 'String', native: '@db.Xml' };
      return { type: 'String' };
    case 'uuid':
      if (dialect === 'postgresql') return { type: 'String', native: '@db.Uuid' };
      if (dialect === 'sqlserver') return { type: 'String', native: '@db.UniqueIdentifier' };
      return { type: 'String' };
    case 'json':
      if (dialect === 'sqlserver') return { type: 'String' };
      if (dialect === 'postgresql' && !logical.binary) return { type: 'Json', native: '@db.Json' };
      return { type: 'Json' };
    case 'bytes':
      return { type: 'Bytes', native: bytesNative(token, raw, dialect) };
    case 'date':
      return { type: 'DateTime', native: dialect === 'sqlite' ? undefined : '@db.Date' };
    case 'time':
      if (dialect === 'postgresql') return { type: 'DateTime', native: `@db.Time${token === 'timetz' ? 'tz' : ''}(${precision ?? 6})` };
      if (dialect === 'mysql') return { type: 'DateTime', native: `@db.Time(${precision ?? 0})` };
      if (dialect === 'sqlserver') return { type: 'DateTime', native: '@db.Time' };
      return { type: 'DateTime' };
    case 'timestamp':
      if (dialect === 'postgresql') {
        return { type: 'DateTime', native: `@db.Timestamp${logical.withTimeZone ? 'tz' : ''}(${precision ?? 6})` };
      }
      if (dialect === 'mysql') {
        return { type: 'DateTime', native: `@db.${token === 'timestamp' ? 'Timestamp' : 'DateTime'}(${precision ?? 0})` };
      }
      if (dialect === 'sqlserver') {
        if (token === 'datetime') return { type: 'DateTime', native: '@db.DateTime' };
        if (token === 'smalldatetime') return { type: 'DateTime', native: '@db.SmallDateTime' };
        if (token === 'datetimeoffset') return { type: 'DateTime', native: '@db.DateTimeOffset' };
        return { type: 'DateTime' };
      }
      return { type: 'DateTime' };
    case 'unknown':
      return { type: `Unsupported(${quote(raw)})` };
  }
}

function stringNative(logical: Extract<LogicalType, { kind: 'string' }>, dialect: PrismaDialect): string | undefined {
  if (dialect === 'sqlite') return undefined;
  const length = logical.length === 'max' ? 'Max' : logical.length;
  if (dialect === 'sqlserver') {
    const base = `${logical.national ? 'N' : ''}${logical.fixed ? 'Char' : 'VarChar'}`;
    return length != null ? `@db.${base}(${length})` : undefined;
  }
  if (length == null || length === 'Max') return undefined;
  return `@db.${logical.fixed ? 'Char' : 'VarChar'}(${length})`;
}

function bytesNative(token: string, raw: string, dialect: PrismaDialect): string | undefined {
  const length = (/\((\d+|max)\)/i.exec(raw) ?? [])[1];
  const size = length == null ? null : length.toLowerCase() === 'max' ? 'Max' : length;
  if (dialect === 'mysql') {
    const blob = { blob: 'Blob', tinyblob: 'TinyBlob', mediumblob: 'MediumBlob', longblob: 'LongBlob' }[token];
    if (blob) return `@db.${blob}`;
    if (token === 'varbinary' && size) return `@db.VarBinary(${size})`;
    if (token === 'binary' && size) return `@db.Binary(${size})`;
  }
  if (dialect === 'sqlserver') {
    if (token === 'varbinary' && size) return `@db.VarBinary(${size})`;
    if (token === 'binary' && size) return `@db.Binary(${size})`;
    if (token === 'image') return '@db.Image';
  }
  return undefined;
}

const NOW = /^(?:current_timestamp(?:\s*\(\s*\d*\s*\))?|now\s*\(\s*\)|getdate\s*\(\s*\)|sysdatetime\s*\(\s*\)|getutcdate\s*\(\s*\)|sysutcdatetime\s*\(\s*\)|localtimestamp(?:\s*\(\s*\d*\s*\))?|systimestamp|sysdate)$/i;

/**
 * 默认值的 SQL 原文 → Prisma 的 `@default(…)` 参数。认得出的字面量与「当前时间」写成 Prisma 的写法，
 * 其余一律 `dbgenerated("原文")`：语义仍由数据库给，客户端只是知道这一列可以不填
 */
export function prismaDefault(sql: string, type: string): string {
  let text = sql.trim();
  // SQL Server 给的默认值外面带括号：((0))、('new')、(getdate())
  while (/^\((.*)\)$/s.test(text) && balanced(text.slice(1, -1))) text = text.slice(1, -1).trim();
  const base = type.replace(/\?$/, '');

  if (base === 'DateTime' && NOW.test(text)) return 'now()';

  // PostgreSQL 的 'new'::text、'0'::numeric：去掉类型转换再认
  const cast = /^(.*?)::[\w\s."()[\],]+$/s.exec(text);
  const literal = cast ? cast[1].trim() : text;
  const stringLiteral = /^N?'((?:[^']|'')*)'$/s.exec(literal);
  const value = stringLiteral ? stringLiteral[1].replace(/''/g, "'") : literal;

  if (base === 'Boolean') {
    if (/^(?:true|1|b'1')$/i.test(value)) return 'true';
    if (/^(?:false|0|b'0')$/i.test(value)) return 'false';
  }
  if (['Int', 'BigInt', 'Float', 'Decimal'].includes(base) && /^[+-]?\d+(?:\.\d+)?$/.test(value)) {
    return value;
  }
  if ((base === 'String' || base === 'Json') && stringLiteral) return quote(value);
  return `dbgenerated(${quote(sql.trim())})`;
}

function balanced(text: string): boolean {
  let depth = 0;
  for (const char of text) {
    if (char === '(') depth += 1;
    if (char === ')') depth -= 1;
    if (depth < 0) return false;
  }
  return depth === 0;
}

function addRelation(relation: RelationPlan, byKey: Map<string, PrismaModel>, notes: CodegenNote[]): void {
  const source = byKey.get(relation.source.key);
  const target = byKey.get(relation.target.key);
  if (!source || !target) return;
  const skip = (reason: 'target-not-unique' | 'ignored-table') => notes.push({
    kind: 'skipped-relation',
    table: relation.source.key,
    constraint: relation.foreignKey.name,
    reason
  });
  if (source.ignored || target.ignored) {
    skip('ignored-table');
    return;
  }
  // references 只能指向主键或唯一约束（MySQL 允许外键指向普通索引，Prisma 不收）
  const referenced = relation.foreignKey.referencedColumns;
  const referencesUnique = sameSet(referenced, target.table.primaryKey)
    || target.table.unique.some((columns) => sameSet(columns, referenced));
  if (!referencesUnique) {
    skip('target-not-unique');
    return;
  }

  const relationName = relation.ambiguous ? `${source.name}${pascalCase(relation.forwardBase)}` : null;
  const forward = source.scope.claim(camelCase(relation.forwardBase));
  const back = target.scope.claim(camelCase(relation.backBase));
  const optional = relation.foreignKey.columns.some(
    (name) => relation.source.columns.find((column) => column.name === name)?.nullable
  );
  const fields = relation.foreignKey.columns.map((name) => source.fieldOf.get(name)).join(', ');
  const references = referenced.map((name) => target.fieldOf.get(name)).join(', ');
  const named = relationName ? `${quote(relationName)}, ` : '';
  // 不写的话 Prisma 按它自己的默认（SetNull / Cascade）推断，SQL Server 上两条外键指向同一张表、
  // 自引用都会被判成「多条级联路径」而校验不过。读到的库没有这一项，照 `db pull` 遇到 NO ACTION 的写法
  const action = relation.foreignKey.onDelete;
  const onDelete = action === 'cascade' ? 'Cascade' : action === 'set null' ? 'SetNull' : 'NoAction';

  source.fields.push({
    name: forward,
    type: `${target.name}${optional ? '?' : ''}`,
    attributes: [`@relation(${named}fields: [${fields}], references: [${references}], onDelete: ${onDelete}, onUpdate: NoAction)`]
  });
  target.fields.push({
    name: back,
    type: relation.oneToOne ? `${source.name}?` : `${source.name}[]`,
    attributes: relationName ? [`@relation(${quote(relationName)})`] : []
  });
}

function sameSet(left: readonly string[], right: readonly string[]): boolean {
  return left.length === right.length && left.every((name) => right.includes(name));
}

function renderModel(model: PrismaModel): string {
  const nameWidth = Math.max(0, ...model.fields.map((field) => field.name.length));
  const typeWidth = Math.max(0, ...model.fields.map((field) => field.type.length));
  const lines: string[] = [];
  if (model.ignored) {
    lines.push('/// The underlying table has no primary key or unique constraint, so Prisma Client cannot use it.');
  }
  lines.push(`model ${model.name} {`);
  for (const field of model.fields) {
    if (field.doc) lines.push(`  /// ${field.doc}`);
    const parts = [field.name.padEnd(nameWidth), field.attributes.length ? field.type.padEnd(typeWidth) : field.type];
    lines.push(`  ${[...parts, ...field.attributes].join(' ')}`.trimEnd());
  }
  if (model.blockAttributes.length) {
    lines.push('');
    lines.push(...model.blockAttributes.map((attribute) => `  ${attribute}`));
  }
  lines.push('}');
  return lines.join('\n');
}

/** Prisma 的字符串字面量：双引号，反斜杠与双引号转义 */
function quote(text: string): string {
  return `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}
