import {
  camelCase,
  logicalType,
  NameScope,
  noteLines,
  pascalCase,
  planRelations,
  type CodegenColumn,
  type CodegenDialect,
  type CodegenNote,
  type CodegenSchema,
  type CodegenTable,
  type GeneratedCode,
  type GeneratedFile,
  type LogicalType,
  type RelationPlan
} from './codegenModel';
import { columnTypeToken } from './columnTypes';
import { entityFileName, TS_RESERVED_PROPERTIES, tsObject, tsString, tsType } from './codegenTs';

/**
 * TypeORM 实体（NestJS 文档的首选）：一张表一个 `*.entity.ts`，外加导出全部实体的 `index.ts`。
 *
 * 列类型不照抄目录原文：TypeORM 建元数据时按驱动的 `supportedDataTypes` 校验，认不得就启动报错。
 * 所以按逻辑类型给各驱动认的名字，原文只在驱动确实认那个写法时保留（MySQL 的几种 text / blob、
 * SQL Server 的几种 datetime）。认不出的不写 `type`，TypeORM 按 TS 类型推断，开头列出来
 */

interface Entity {
  table: CodegenTable;
  className: string;
  fileName: string;
  /** 列名 → 属性名 */
  propertyOf: Map<string, string>;
  scope: NameScope;
  members: string[][];
  imports: Set<string>;
  entityImports: Set<string>;
}

export function generateTypeorm(schema: CodegenSchema, source: string): GeneratedCode {
  const notes: CodegenNote[] = [];
  const classScope = new NameScope();
  const fileScope = new NameScope();
  const multiSchema = new Set(schema.tables.map((table) => table.schema)).size > 1;

  const entities: Entity[] = [];
  const skipped = new Set<string>();
  for (const table of schema.tables) {
    if (table.primaryKey.length === 0) {
      notes.push({ kind: 'skipped-table', table: table.key, reason: 'no-primary-key' });
      skipped.add(table.key);
      continue;
    }
    const plain = pascalCase(table.name);
    const className = classScope.claim(
      multiSchema && table.schema && schema.tables.some((other) => other !== table && pascalCase(other.name) === plain)
        ? pascalCase(`${table.schema}_${table.name}`)
        : plain
    );
    const scope = new NameScope(TS_RESERVED_PROPERTIES);
    const propertyOf = new Map(table.columns.map((column) => [column.name, scope.claim(camelCase(column.name))]));
    const entity: Entity = {
      table,
      className,
      fileName: entityFileName(table.name, fileScope),
      propertyOf,
      scope,
      members: [],
      imports: new Set(['Entity']),
      entityImports: new Set()
    };
    for (const column of table.columns) {
      entity.members.push(columnMember(entity, column, schema.dialect, notes));
    }
    entities.push(entity);
  }

  const byKey = new Map(entities.map((entity) => [entity.table.key, entity]));
  const { relations, dangling } = planRelations(schema);
  for (const item of dangling) {
    notes.push({ kind: 'dangling-foreign-key', table: item.table.key, constraint: item.foreignKey.name, referencedTable: item.foreignKey.referencedTable });
  }
  for (const relation of relations) {
    const source = byKey.get(relation.source.key);
    const target = byKey.get(relation.target.key);
    if (!source || !target) {
      notes.push({ kind: 'skipped-relation', table: relation.source.key, constraint: relation.foreignKey.name, reason: 'skipped-table' });
      continue;
    }
    addRelation(relation, source, target);
  }

  const header = `// Generated by DataOmni from ${source}.`;
  const files: GeneratedFile[] = entities.map((entity) => ({
    path: entity.fileName,
    contents: renderEntity(entity, schema.dialect, byKey, header)
  }));
  files.push({ path: 'index.ts', contents: renderIndex(entities, notes, header) });
  return { files, notes };
}

function columnMember(entity: Entity, column: CodegenColumn, dialect: CodegenDialect, notes: CodegenNote[]): string[] {
  const table = entity.table;
  const logical = logicalType(column.dataType, dialect);
  const known = typeormColumnType(logical, column.dataType, dialect);
  if (!known.type) notes.push({ kind: 'unknown-type', table: table.key, column: column.name, dataType: column.dataType });
  const mapped = known.type ? known : { type: fallbackType(column.dataType, dialect), extra: [] };
  const property = entity.propertyOf.get(column.name) ?? column.name;
  const isPrimary = table.primaryKey.includes(column.name);
  const generated = isPrimary && table.primaryKey.length === 1 && column.autoIncrement && logical.kind === 'int';

  const options: Array<[string, string]> = [];
  if (property !== column.name) options.push(['name', tsString(column.name)]);
  if (mapped.type) options.push(['type', tsString(mapped.type)]);
  // PrimaryGeneratedColumn 只收类型，不收精度、长度（类型声明里就没有）
  if (!generated) options.push(...mapped.extra);
  if (!generated && column.nullable && !isPrimary) options.push(['nullable', 'true']);
  if (table.unique.some((columns) => columns.length === 1 && columns[0] === column.name)) options.push(['unique', 'true']);
  if (column.defaultValue != null && !generated) options.push(['default', `() => ${tsString(column.defaultValue)}`]);
  if (column.computed) options.push(['insert', 'false'], ['update', 'false']);

  const decorator = generated ? 'PrimaryGeneratedColumn' : isPrimary ? 'PrimaryColumn' : 'Column';
  entity.imports.add(decorator);
  const nullable = column.nullable && !isPrimary;
  const lines = column.computed ? ['/** Computed by the database; read only. */'] : [];
  lines.push(
    `@${decorator}(${options.length ? tsObject(options) : ''})`,
    `${property}!: ${tsType(logical, dialect)}${nullable ? ' | null' : ''};`
  );
  return lines;
}

/** 各驱动认的列类型名（TypeORM 的 `supportedDataTypes`），外加长度、精度、无符号 */
function typeormColumnType(
  logical: LogicalType,
  raw: string,
  dialect: CodegenDialect
): { type: string | null; extra: Array<[string, string]> } {
  const token = columnTypeToken(raw.toLowerCase());
  const plain = (type: string | null) => ({ type, extra: [] as Array<[string, string]> });
  switch (logical.kind) {
    case 'int':
      return typeormIntType(logical, token, raw, dialect);
    case 'decimal': {
      const extra: Array<[string, string]> = [];
      if (logical.precision != null) extra.push(['precision', String(logical.precision)]);
      if (logical.precision != null && logical.scale != null) extra.push(['scale', String(logical.scale)]);
      if (dialect === 'oracle') return { type: 'number', extra };
      if (token === 'money' && (dialect === 'postgresql' || dialect === 'sqlserver')) return plain('money');
      if (token === 'smallmoney' && dialect === 'sqlserver') return plain('smallmoney');
      return { type: dialect === 'postgresql' ? 'numeric' : 'decimal', extra };
    }
    case 'float': {
      const names: Record<CodegenDialect, [string, string]> = {
        postgresql: ['real', 'double precision'],
        mysql: ['float', 'double'],
        sqlite: ['real', 'real'],
        sqlserver: ['real', 'float'],
        // TypeORM 的 Oracle 驱动不认 binary_float / binary_double（类型声明里也没有）
        oracle: ['real', 'double precision']
      };
      return plain(names[dialect][logical.bytes === 4 ? 0 : 1]);
    }
    case 'bool':
      // Oracle 23ai 的 BOOLEAN TypeORM 不认，按 NUMBER(1) 读写
      return plain(dialect === 'sqlserver' ? 'bit' : dialect === 'oracle' ? 'number' : 'boolean');
    case 'string': {
      const names: Record<CodegenDialect, string> = {
        postgresql: logical.fixed ? 'character' : 'character varying',
        mysql: logical.fixed ? 'char' : 'varchar',
        sqlite: logical.fixed ? 'character' : 'varchar',
        sqlserver: `${logical.national ? 'n' : ''}${logical.fixed ? 'char' : 'varchar'}`,
        oracle: logical.fixed ? (logical.national ? 'nchar' : 'char') : logical.national ? 'nvarchar2' : 'varchar2'
      };
      const length = logical.length === 'max' ? tsString('MAX') : logical.length != null ? String(logical.length) : null;
      return { type: names[dialect], extra: length ? [['length', length]] : [] };
    }
    case 'text': {
      if (dialect === 'mysql') return plain(['text', 'tinytext', 'mediumtext', 'longtext'].includes(token) ? token : 'text');
      if (dialect === 'sqlserver') return plain(token === 'ntext' ? 'ntext' : 'text');
      if (dialect === 'oracle') return plain(token === 'nclob' ? 'nclob' : 'clob');
      if (dialect === 'postgresql' && (token === 'citext' || token === 'xml')) return plain(token);
      return plain('text');
    }
    case 'uuid':
      return plain(dialect === 'postgresql' ? 'uuid' : dialect === 'sqlserver' ? 'uniqueidentifier' : null);
    case 'json':
      if (dialect === 'postgresql') return plain(logical.binary ? 'jsonb' : 'json');
      // SQLite 没有 json 类型，存的是 JSON 文本：simple-json 读写时替你 parse / stringify
      return plain(dialect === 'mysql' || dialect === 'oracle' ? 'json' : 'simple-json');
    case 'bytes': {
      if (dialect === 'postgresql') return plain('bytea');
      if (dialect === 'sqlite') return plain('blob');
      if (dialect === 'oracle') return plain(token === 'raw' ? 'raw' : 'blob');
      const length = /\((\d+|max)\)/i.exec(raw)?.[1];
      const extra: Array<[string, string]> = length ? [['length', /max/i.test(length) ? tsString('MAX') : length]] : [];
      if (dialect === 'mysql') {
        if (['blob', 'tinyblob', 'mediumblob', 'longblob'].includes(token)) return plain(token);
        return { type: token === 'binary' ? 'binary' : 'varbinary', extra };
      }
      if (token === 'image' || token === 'rowversion' || token === 'timestamp') return plain(token === 'image' ? 'image' : 'rowversion');
      return { type: token === 'binary' ? 'binary' : 'varbinary', extra };
    }
    case 'date':
      return plain('date');
    case 'time':
      if (dialect === 'oracle' || dialect === 'sqlite' && token !== 'time') return plain(null);
      return plain(dialect === 'postgresql' && token === 'timetz' ? 'time with time zone' : 'time');
    case 'timestamp':
      return plain(typeormTimestampType(logical.withTimeZone, token, dialect));
    case 'unknown':
      return plain(null);
  }
}

/**
 * 映射不了的类型也得写一个 `type`：不写的话 TypeORM 拿装饰器元数据推断，而 `string | null`
 * 在元数据里只剩 `Object`，建元数据时报「Data type "Object" is not supported」，整个应用起不来。
 * 驱动本来就认的原文照写（`interval`、`year`、`geography`），其余写成这个库的长文本
 */
const PASSTHROUGH_TYPES: Record<CodegenDialect, ReadonlySet<string>> = {
  postgresql: new Set([
    'interval', 'point', 'line', 'lseg', 'box', 'path', 'polygon', 'circle', 'cidr', 'inet', 'macaddr', 'macaddr8',
    'tsvector', 'tsquery', 'hstore', 'ltree', 'bit', 'varbit', 'int4range', 'int8range', 'numrange', 'tsrange',
    'tstzrange', 'daterange', 'geometry', 'geography'
  ]),
  mysql: new Set(['year', 'bit', 'geometry', 'point', 'linestring', 'polygon', 'multipoint', 'multilinestring', 'multipolygon', 'geometrycollection']),
  sqlite: new Set(),
  sqlserver: new Set(['geography', 'geometry', 'hierarchyid', 'sql_variant', 'xml']),
  oracle: new Set(['rowid', 'urowid', 'long', 'bfile'])
};

const FALLBACK_TEXT: Record<CodegenDialect, string> = {
  postgresql: 'text',
  mysql: 'text',
  sqlite: 'text',
  sqlserver: 'nvarchar',
  oracle: 'clob'
};

function fallbackType(raw: string, dialect: CodegenDialect): string {
  const token = columnTypeToken(raw.toLowerCase());
  return PASSTHROUGH_TYPES[dialect].has(token) ? token : FALLBACK_TEXT[dialect];
}

function typeormIntType(
  logical: Extract<LogicalType, { kind: 'int' }>,
  token: string,
  raw: string,
  dialect: CodegenDialect
): { type: string; extra: Array<[string, string]> } {
  const byBytes = { 1: 'tinyint', 2: 'smallint', 4: 'int', 8: 'bigint' } as const;
  switch (dialect) {
    case 'postgresql':
      return { type: logical.bytes === 2 ? 'smallint' : logical.bytes === 8 ? 'bigint' : 'integer', extra: [] };
    case 'mysql':
      return {
        type: token === 'mediumint' ? 'mediumint' : byBytes[logical.bytes],
        extra: logical.unsigned ? [['unsigned', 'true']] : []
      };
    case 'sqlite':
      return { type: 'integer', extra: [] };
    case 'sqlserver':
      return { type: byBytes[logical.bytes], extra: [] };
    case 'oracle': {
      const precision = /\((\d+)\)/.exec(raw)?.[1];
      return { type: 'number', extra: precision ? [['precision', precision]] : [] };
    }
  }
}

function typeormTimestampType(withTimeZone: boolean, token: string, dialect: CodegenDialect): string {
  switch (dialect) {
    case 'postgresql':
      return withTimeZone ? 'timestamp with time zone' : 'timestamp';
    case 'mysql':
      return token === 'timestamp' ? 'timestamp' : 'datetime';
    case 'sqlite':
      return 'datetime';
    case 'sqlserver':
      return ['datetime', 'datetime2', 'smalldatetime', 'datetimeoffset'].includes(token) ? token : 'datetime2';
    case 'oracle':
      return token === 'date' ? 'date' : withTimeZone ? 'timestamp with time zone' : 'timestamp';
  }
}

function addRelation(relation: RelationPlan, source: Entity, target: Entity): void {
  const forward = source.scope.claim(camelCase(relation.forwardBase));
  const back = target.scope.claim(camelCase(relation.backBase));
  const nullable = relation.foreignKey.columns.some(
    (name) => relation.source.columns.find((column) => column.name === name)?.nullable
  );
  const joinColumns = relation.foreignKey.columns.map((name, index) => tsObject([
    ['name', tsString(name)],
    ['referencedColumnName', tsString(target.propertyOf.get(relation.foreignKey.referencedColumns[index]) ?? '')]
  ]));
  const kind = relation.oneToOne ? 'OneToOne' : 'ManyToOne';
  const onDelete = relation.foreignKey.onDelete ? `, onDelete: ${tsString(relation.foreignKey.onDelete.toUpperCase())}` : '';
  const variable = camelCase(target.className, 'item');
  source.imports.add(kind).add('JoinColumn');
  source.entityImports.add(target.table.key);
  source.members.push([
    `@${kind}(() => ${target.className}, (${variable}) => ${variable}.${back}, { nullable: ${nullable}${onDelete} })`,
    `@JoinColumn(${joinColumns.length === 1 ? joinColumns[0] : `[${joinColumns.join(', ')}]`})`,
    `${forward}!: Relation<${target.className}>${nullable ? ' | null' : ''};`
  ]);

  const sourceVariable = camelCase(source.className, 'item');
  target.entityImports.add(source.table.key);
  if (relation.oneToOne) {
    target.imports.add('OneToOne');
    target.members.push([
      `@OneToOne(() => ${source.className}, (${sourceVariable}) => ${sourceVariable}.${forward})`,
      `${back}!: Relation<${source.className}> | null;`
    ]);
  } else {
    target.imports.add('OneToMany');
    target.members.push([
      `@OneToMany(() => ${source.className}, (${sourceVariable}) => ${sourceVariable}.${forward})`,
      `${back}!: Relation<${source.className}>[];`
    ]);
  }
}

function renderEntity(entity: Entity, dialect: CodegenDialect, byKey: Map<string, Entity>, header: string): string {
  const table = entity.table;
  const composites = table.unique.filter((columns) => columns.length > 1);
  if (composites.length) entity.imports.add('Unique');
  const usesRelation = entity.members.some((member) => member.some((line) => line.includes('Relation<')));
  const typeormImports = [...entity.imports].sort();
  const lines = [header, `import { ${typeormImports.join(', ')} } from 'typeorm';`];
  if (usesRelation) lines.push("import type { Relation } from 'typeorm';");
  for (const key of [...entity.entityImports].filter((key) => key !== table.key).sort()) {
    const other = byKey.get(key);
    if (other) lines.push(`import { ${other.className} } from './${other.fileName.replace(/\.ts$/, '')}';`);
  }
  lines.push('');

  const entityOptions: Array<[string, string]> = [['name', tsString(table.name)]];
  if (table.schema && dialect !== 'mysql' && dialect !== 'sqlite') entityOptions.push(['schema', tsString(table.schema)]);
  lines.push(`@Entity(${tsObject(entityOptions)})`);
  for (const columns of composites) {
    lines.push(`@Unique([${columns.map((name) => tsString(entity.propertyOf.get(name) ?? name)).join(', ')}])`);
  }
  lines.push(`export class ${entity.className} {`);
  entity.members.forEach((member, index) => {
    if (index > 0) lines.push('');
    lines.push(...member.map((line) => `  ${line}`));
  });
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

function renderIndex(entities: Entity[], notes: CodegenNote[], header: string): string {
  const lines = [header, ...noteLines(notes).map((line) => `// - ${line}`)];
  for (const entity of entities) {
    lines.push(`import { ${entity.className} } from './${entity.fileName.replace(/\.ts$/, '')}';`);
  }
  lines.push('');
  lines.push(`export { ${entities.map((entity) => entity.className).join(', ')} };`);
  lines.push('');
  lines.push('/** Pass to `TypeOrmModule.forRoot({ entities })` or `new DataSource({ entities })`. */');
  lines.push(`export const entities = [${entities.map((entity) => entity.className).join(', ')}];`);
  return `${lines.join('\n')}\n`;
}
