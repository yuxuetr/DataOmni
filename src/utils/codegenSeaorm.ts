import {
  logicalType,
  NameScope,
  noteLines,
  pascalCase,
  planRelations,
  snakeCase,
  type CodegenDialect,
  type CodegenNote,
  type CodegenSchema,
  type CodegenTable,
  type GeneratedCode,
  type GeneratedFile,
  type RelationPlan
} from './codegenModel';
import { escapeRustKeyword, RUST_KEYWORDS, rustString, rustType, SEAORM_TYPES } from './codegenRust';

/**
 * SeaORM 实体，布局同 `sea-orm-cli generate entity`：一张表一个模块，外加 `mod.rs` 与 `prelude.rs`。
 * SeaORM（开源版）支持 PostgreSQL、MySQL、SQLite。
 *
 * 关系的硬规则：`Related<T>` 对同一个 T 只能实现一次，`has_many` / `has_one` 又要求对面实现了
 * `Related<本表>`。所以两张表之间不止一条关系（同向两条、一来一回、自引用）时，只留外键一侧的
 * `belongs_to`，不写反向与 `Related`——要用时 `Relation::Buyer.def()` 照样拿得到
 */
export type SeaormDialect = Extract<CodegenDialect, 'postgresql' | 'mysql' | 'sqlite'>;

export function isSeaormDialect(dialect: CodegenDialect): dialect is SeaormDialect {
  return dialect === 'postgresql' || dialect === 'mysql' || dialect === 'sqlite';
}

interface Module {
  table: CodegenTable;
  name: string;
  entityAlias: string;
  /** 列名 → 字段名 */
  fieldOf: Map<string, string>;
  fields: string[];
  hasFloat: boolean;
  variants: NameScope;
  relations: string[][];
  related: string[];
}

export function generateSeaorm(schema: CodegenSchema & { dialect: SeaormDialect }, source: string): GeneratedCode {
  const notes: CodegenNote[] = [];
  const moduleScope = new NameScope(new Set([...RUST_KEYWORDS, 'prelude']), escapeRustKeyword);
  const aliasScope = new NameScope(new Set(['Self']), (name) => `${name}Entity`);
  const multiSchema = new Set(schema.tables.map((table) => table.schema)).size > 1;

  const modules: Module[] = [];
  for (const table of schema.tables) {
    if (table.primaryKey.length === 0) {
      notes.push({ kind: 'skipped-table', table: table.key, reason: 'no-primary-key' });
      continue;
    }
    const qualified = multiSchema && table.schema
      && schema.tables.some((other) => other !== table && snakeCase(other.name) === snakeCase(table.name));
    const base = qualified ? `${table.schema}_${table.name}` : table.name;
    const module: Module = {
      table,
      name: moduleScope.claim(snakeCase(base, 'table')),
      entityAlias: aliasScope.claim(pascalCase(base)),
      fieldOf: new Map(),
      fields: [],
      hasFloat: false,
      variants: new NameScope(new Set(['Self']), (name) => `${name}Relation`),
      relations: [],
      related: []
    };
    buildFields(module, schema.dialect, notes);
    modules.push(module);
  }

  const byKey = new Map(modules.map((module) => [module.table.key, module]));
  const { relations, dangling } = planRelations(schema);
  for (const item of dangling) {
    notes.push({ kind: 'dangling-foreign-key', table: item.table.key, constraint: item.foreignKey.name, referencedTable: item.foreignKey.referencedTable });
  }
  // 两张表之间的关系条数（不分方向）：只有恰好一条时才写反向与 Related
  const pairCount = new Map<string, number>();
  const pairKey = (relation: RelationPlan) => [relation.source.key, relation.target.key].sort().join('\u0000');
  for (const relation of relations) pairCount.set(pairKey(relation), (pairCount.get(pairKey(relation)) ?? 0) + 1);

  for (const relation of relations) {
    const source = byKey.get(relation.source.key);
    const target = byKey.get(relation.target.key);
    if (!source || !target) {
      notes.push({ kind: 'skipped-relation', table: relation.source.key, constraint: relation.foreignKey.name, reason: 'skipped-table' });
      continue;
    }
    const unique = pairCount.get(pairKey(relation)) === 1 && source !== target;
    addRelation(relation, source, target, unique);
  }

  const header = `//! \`SeaORM\` entity, generated by DataOmni from ${source}.`;
  const files: GeneratedFile[] = modules.map((module) => ({
    path: `${module.name}.rs`,
    contents: renderModule(module, schema.dialect, header)
  }));
  files.push({
    path: 'mod.rs',
    contents: [
      header,
      '//! Needs sea-orm with the `with-chrono`, `with-uuid`, `with-rust_decimal` and `with-json` features for the types used below.',
      ...noteLines(notes).map((line) => `//! - ${line}`),
      '',
      'pub mod prelude;',
      '',
      ...modules.map((module) => `pub mod ${module.name};`),
      ''
    ].join('\n')
  });
  files.push({
    path: 'prelude.rs',
    contents: [header, '', ...modules.map((module) => `pub use super::${module.name}::Entity as ${module.entityAlias};`), ''].join('\n')
  });
  return { files, notes };
}

function buildFields(module: Module, dialect: SeaormDialect, notes: CodegenNote[]): void {
  const table = module.table;
  const scope = new NameScope(RUST_KEYWORDS, escapeRustKeyword);
  for (const column of table.columns) {
    const field = scope.claim(snakeCase(column.name));
    module.fieldOf.set(column.name, field);
    const logical = logicalType(column.dataType, dialect);
    const mapped = rustType(logical, dialect, SEAORM_TYPES);
    if (!mapped) notes.push({ kind: 'unknown-type', table: table.key, column: column.name, dataType: column.dataType });
    if (logical.kind === 'float') module.hasFloat = true;

    const attributes: string[] = [];
    const isPrimary = table.primaryKey.includes(column.name);
    if (isPrimary) {
      attributes.push('primary_key');
      // 单列整数主键 SeaORM 默认当自增；不是自增的要说出来，不然新增时不带这一列
      if (!(column.autoIncrement && table.primaryKey.length === 1 && logical.kind === 'int')) {
        attributes.push('auto_increment = false');
      }
    }
    if (field !== column.name) attributes.push(`column_name = ${rustString(column.name)}`);
    if (!mapped) attributes.push(`column_type = ${rustString(`custom(${rustString(column.dataType.trim())})`)}`);
    if (table.unique.some((columns) => columns.length === 1 && columns[0] === column.name)) attributes.push('unique');
    const type = mapped ?? 'String';
    const nullable = column.nullable && !isPrimary;
    if (attributes.length) module.fields.push(`    #[sea_orm(${attributes.join(', ')})]`);
    module.fields.push(`    pub ${field}: ${nullable ? `Option<${type}>` : type},`);
  }
}

function columnVariant(module: Module, column: string, prefix: string): string {
  return `${prefix}Column::${pascalCase(module.fieldOf.get(column) ?? column, 'Column')}`;
}

function columnList(module: Module, columns: string[], prefix: string): string {
  const variants = columns.map((column) => columnVariant(module, column, prefix));
  return variants.length === 1 ? variants[0] : `(${variants.join(', ')})`;
}

function addRelation(relation: RelationPlan, source: Module, target: Module, unique: boolean): void {
  const self = source === target;
  const targetPath = self ? 'Entity' : `super::${target.name}::Entity`;
  const targetPrefix = self ? '' : `super::${target.name}::`;
  const onDelete = relation.foreignKey.onDelete === 'cascade' ? 'Cascade' : relation.foreignKey.onDelete === 'set null' ? 'SetNull' : 'NoAction';
  const forward = source.variants.claim(pascalCase(relation.forwardBase, 'Relation'));
  source.relations.push([
    '    #[sea_orm(',
    `        belongs_to = ${rustString(targetPath)},`,
    `        from = ${rustString(columnList(source, relation.foreignKey.columns, ''))},`,
    `        to = ${rustString(columnList(target, relation.foreignKey.referencedColumns, targetPrefix))},`,
    '        on_update = "NoAction",',
    `        on_delete = ${rustString(onDelete)}`,
    '    )]',
    `    ${forward},`
  ]);
  if (!unique) return;

  source.related.push(
    `impl Related<super::${target.name}::Entity> for Entity {\n    fn to() -> RelationDef {\n        Relation::${forward}.def()\n    }\n}`
  );
  const back = target.variants.claim(pascalCase(relation.backBase, 'Relation'));
  target.relations.push([
    `    #[sea_orm(${relation.oneToOne ? 'has_one' : 'has_many'} = ${rustString(`super::${source.name}::Entity`)})]`,
    `    ${back},`
  ]);
  target.related.push(
    `impl Related<super::${source.name}::Entity> for Entity {\n    fn to() -> RelationDef {\n        Relation::${back}.def()\n    }\n}`
  );
}

function renderModule(module: Module, dialect: SeaormDialect, header: string): string {
  const table = module.table;
  // f32 / f64 没有 Eq；其余字段类型（含 Decimal、Json）都有
  const derives = ['Clone', 'Debug', 'PartialEq', 'DeriveEntityModel', ...(module.hasFloat ? [] : ['Eq'])];
  const tableAttributes = [`table_name = ${rustString(table.name)}`];
  if (table.schema && dialect === 'postgresql') tableAttributes.push(`schema_name = ${rustString(table.schema)}`);
  const lines = [
    header,
    '',
    'use sea_orm::entity::prelude::*;',
    '',
    `#[derive(${derives.join(', ')})]`,
    `#[sea_orm(${tableAttributes.join(', ')})]`,
    'pub struct Model {',
    ...module.fields,
    '}',
    '',
    '#[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]',
    `pub enum Relation {${module.relations.length ? '' : '}'}`
  ];
  if (module.relations.length) {
    module.relations.forEach((relation, index) => {
      if (index > 0) lines.push('');
      lines.push(...relation);
    });
    lines.push('}');
  }
  for (const related of module.related) lines.push('', related);
  lines.push('', 'impl ActiveModelBehavior for ActiveModel {}', '');
  return lines.join('\n');
}
