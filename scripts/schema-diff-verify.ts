/**
 * 结构比对的往返验收（rfcs/schema-diff.md §6）：在真库上建两份不同的结构 src、dst，比出「把 dst 改成 src」
 * 的脚本，在 dst 上执行，**再比一次必须为空**。比对、出脚本、读目录都用应用里同一份代码与查询。
 *
 * 由 scripts/schema-diff-verify.sh 调用：它先把目录查询写进 `QUERIES` 指的 JSON，SQL Server 的驱动装进
 * `MSSQL_MODULE`。连接串同冒烟测试（DATAOMNI_POSTGRES_TEST_URL 等），只在 shell 里传。
 *
 *   bun scripts/schema-diff-verify.ts [--skip-kind=<差异种类>]
 *
 * `--skip-kind` 是反向验证：不同步某一种差异，第二次比对就不该为空、退出码就该非零。
 */
import { Database } from 'bun:sqlite';
import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import type { SchemaMetadataQueries } from '../src/utils/catalogQueries';
import { diffSchemas, type SchemaDiff, type SchemaDiffDialect, type SchemaDifference, type SchemaSnapshot } from '../src/utils/schemaDiff';
import { listTables, loadSchemaSnapshot, readNativeDdl, type ErDiagramQueries } from '../src/utils/schemaSnapshot';
import { buildSyncScript, isSyncable, renderSyncScript } from '../src/utils/schemaSync';

type Select = (sql: string, params: unknown[]) => Promise<unknown>;
interface Side {
  select: Select;
  exec: (sql: string) => Promise<void>;
  /** ER 查询要绑的库名（MySQL） */
  database: string | null;
  /** 只比这个 schema（PostgreSQL、SQL Server 在同一个库里放两份） */
  schema: string | null;
}
interface Case {
  dialect: SchemaDiffDialect;
  src: Side;
  dst: Side;
  /** 第一次比对至少要有这些种类，否则这次往返什么也没验 */
  expectedKinds: SchemaDifference['kind'][];
  close: () => Promise<void>;
}

const queries = JSON.parse(readFileSync(process.env.QUERIES ?? '', 'utf8')) as Record<string, { er: ErDiagramQueries; metadata: SchemaMetadataQueries }>;
const skipKind = process.argv.find((arg) => arg.startsWith('--skip-kind='))?.slice('--skip-kind='.length) ?? null;
const t = ((key: string) => key) as Parameters<typeof buildSyncScript>[2]['t'];

/** MySQL 的 information_schema 名字列在 `lower_case_table_names=0` 时是 VARBINARY，驱动给字节；应用的解码器给字符串 */
const decodeRow = (row: Record<string, unknown>) =>
  Object.fromEntries(Object.entries(row).map(([key, value]) => [key, value instanceof Uint8Array ? new TextDecoder().decode(value) : value]));

const ALL_KINDS: SchemaDifference['kind'][] = [
  'table-added', 'table-removed', 'column-added', 'column-removed', 'column-changed',
  'index-added', 'index-removed', 'foreign-key-added', 'foreign-key-removed'
];

function sqliteCase(): Case {
  const dir = mkdtempSync(join(tmpdir(), 'schema-diff-'));
  const open = (name: string, ddl: string): Side => {
    const db = new Database(join(dir, `${name}.db`));
    db.exec(ddl);
    return {
      select: async (sql, params) => db.query(sql).all(...(params as never[])),
      exec: async (sql) => { db.exec(sql); },
      database: null,
      schema: null
    };
  };
  return {
    dialect: 'sqlite',
    src: open('src', `
      CREATE TABLE users (id INTEGER PRIMARY KEY, email TEXT NOT NULL, name TEXT);
      CREATE UNIQUE INDEX ux_users_email ON users (email);
      CREATE TABLE orders (id INTEGER PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users (id), note TEXT);
      CREATE INDEX ix_orders_user ON orders (user_id);
      CREATE TABLE tags (id INTEGER PRIMARY KEY, label TEXT NOT NULL UNIQUE);`),
    dst: open('dst', `
      CREATE TABLE users (id INTEGER PRIMARY KEY, email TEXT NOT NULL, legacy TEXT);
      CREATE INDEX ix_users_legacy ON users (legacy);
      CREATE TABLE orders (id INTEGER PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users (id), note TEXT);
      CREATE TABLE old_stuff (id INTEGER PRIMARY KEY);`),
    // SQLite 改不了列的类型、可空、默认值，也不能事后加删外键：这几种由单测钉住拒绝
    expectedKinds: ['table-added', 'table-removed', 'column-added', 'column-removed', 'index-added', 'index-removed'],
    close: async () => {}
  };
}

async function postgresCase(url: string): Promise<Case> {
  const sql = new Bun.SQL(url);
  await sql.unsafe(`
    DROP SCHEMA IF EXISTS sd_src CASCADE; DROP SCHEMA IF EXISTS sd_dst CASCADE;
    CREATE SCHEMA sd_src; CREATE SCHEMA sd_dst;
    CREATE TABLE sd_src.users (id serial PRIMARY KEY, email varchar(128) NOT NULL, name varchar(64),
      created_at timestamp DEFAULT now(), CONSTRAINT users_email_key UNIQUE (email));
    CREATE TABLE sd_src.orders (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id integer NOT NULL REFERENCES sd_src.users (id) ON DELETE CASCADE, total numeric(10,2) DEFAULT 0, note text);
    CREATE INDEX ix_orders_user ON sd_src.orders (user_id);
    CREATE TABLE sd_src.tags (id serial PRIMARY KEY, label varchar(32) NOT NULL UNIQUE);
    CREATE TABLE sd_dst.users (id serial PRIMARY KEY, email varchar(64), legacy text, created_at timestamp,
      CONSTRAINT users_created_key UNIQUE (created_at));
    CREATE INDEX ix_users_email ON sd_dst.users (email);
    CREATE TABLE sd_dst.orders (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id integer NOT NULL,
      total numeric(10,2), note text, CONSTRAINT old_fk FOREIGN KEY (user_id) REFERENCES sd_dst.users (id));
    CREATE TABLE sd_dst.old_stuff (id integer PRIMARY KEY);`);
  const side = (schema: string): Side => ({
    select: (text, params) => sql.unsafe(text, params as never[]),
    exec: async (text) => { await sql.unsafe(text); },
    database: null,
    schema
  });
  return {
    dialect: 'postgresql',
    src: side('sd_src'),
    dst: side('sd_dst'),
    expectedKinds: ALL_KINDS,
    close: async () => {
      await sql.unsafe('DROP SCHEMA IF EXISTS sd_src CASCADE; DROP SCHEMA IF EXISTS sd_dst CASCADE;');
      await sql.close();
    }
  };
}

async function mysqlCase(url: string): Promise<Case> {
  const admin = new Bun.SQL(url);
  for (const statement of [
    'DROP DATABASE IF EXISTS dataomni_sd_src', 'DROP DATABASE IF EXISTS dataomni_sd_dst',
    'CREATE DATABASE dataomni_sd_src', 'CREATE DATABASE dataomni_sd_dst',
    `CREATE TABLE dataomni_sd_src.users (id int AUTO_INCREMENT PRIMARY KEY, email varchar(128) NOT NULL, name varchar(64),
      created_at timestamp NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY users_email_key (email))`,
    `CREATE TABLE dataomni_sd_src.orders (id int AUTO_INCREMENT PRIMARY KEY, user_id int NOT NULL, total decimal(10,2) DEFAULT 0,
      note text, KEY ix_orders_user (user_id),
      CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES dataomni_sd_src.users (id) ON DELETE CASCADE)`,
    'CREATE TABLE dataomni_sd_src.tags (id int AUTO_INCREMENT PRIMARY KEY, label varchar(32) NOT NULL, UNIQUE KEY (label))',
    `CREATE TABLE dataomni_sd_dst.users (id int AUTO_INCREMENT PRIMARY KEY, email varchar(64) NULL, legacy text,
      created_at timestamp NULL, KEY ix_users_email (email), UNIQUE KEY users_created_key (created_at))`,
    `CREATE TABLE dataomni_sd_dst.orders (id int AUTO_INCREMENT PRIMARY KEY, user_id int NOT NULL, total decimal(10,2), note text,
      CONSTRAINT old_fk FOREIGN KEY (user_id) REFERENCES dataomni_sd_dst.users (id))`,
    'CREATE TABLE dataomni_sd_dst.old_stuff (id int PRIMARY KEY)'
  ]) {
    await admin.unsafe(statement);
  }
  const open = (database: string): Side & { sql: InstanceType<typeof Bun.SQL> } => {
    const target = new URL(url);
    target.pathname = `/${database}`;
    const sql = new Bun.SQL(target.toString());
    return {
      sql,
      select: async (text, params) => ((await sql.unsafe(text, params as never[])) as Array<Record<string, unknown>>).map(decodeRow),
      exec: async (text) => { await sql.unsafe(text); },
      database,
      schema: null
    };
  };
  const src = open('dataomni_sd_src');
  const dst = open('dataomni_sd_dst');
  return {
    dialect: 'mysql',
    src,
    dst,
    expectedKinds: ALL_KINDS,
    close: async () => {
      await src.sql.close();
      await dst.sql.close();
      await admin.unsafe('DROP DATABASE IF EXISTS dataomni_sd_src');
      await admin.unsafe('DROP DATABASE IF EXISTS dataomni_sd_dst');
      await admin.close();
    }
  };
}

async function sqlServerCase(url: string): Promise<Case> {
  const mssql = (await import(process.env.MSSQL_MODULE ?? 'mssql')).default;
  const parsed = new URL(url);
  const pool = await new mssql.ConnectionPool({
    server: parsed.hostname,
    port: Number(parsed.port || 1433),
    user: decodeURIComponent(parsed.username),
    password: decodeURIComponent(parsed.password),
    database: parsed.pathname.slice(1),
    // 经 ssh 转发连 127.0.0.1：Node 的 TLS 不许拿 IP 当 ServerName，测试库不加密
    options: { trustServerCertificate: true, encrypt: false }
  }).connect();
  const batch = async (text: string) => { await pool.request().batch(text); };
  const cleanup = `
    DROP TABLE IF EXISTS sd_src.orders, sd_src.tags, sd_src.users, sd_dst.orders, sd_dst.tags, sd_dst.old_stuff, sd_dst.users;
    DROP SCHEMA IF EXISTS sd_src; DROP SCHEMA IF EXISTS sd_dst;`;
  await batch(cleanup);
  await batch('CREATE SCHEMA sd_src');
  await batch('CREATE SCHEMA sd_dst');
  await batch(`
    CREATE TABLE sd_src.users (id int IDENTITY(1,1) PRIMARY KEY, email nvarchar(128) NOT NULL CONSTRAINT users_email_key UNIQUE,
      name nvarchar(64), created_at datetime2 CONSTRAINT df_users_created DEFAULT sysdatetime());
    CREATE TABLE sd_src.orders (id int IDENTITY(1,1) PRIMARY KEY,
      user_id int NOT NULL CONSTRAINT fk_orders_user REFERENCES sd_src.users (id) ON DELETE CASCADE,
      total decimal(10,2) CONSTRAINT df_orders_total DEFAULT 0, note nvarchar(max));
    CREATE INDEX ix_orders_user ON sd_src.orders (user_id);
    CREATE TABLE sd_src.tags (id int IDENTITY(1,1) PRIMARY KEY, label nvarchar(32) NOT NULL UNIQUE);
    CREATE TABLE sd_dst.users (id int IDENTITY(1,1) PRIMARY KEY, email nvarchar(64) NULL, legacy nvarchar(max), created_at datetime2,
      CONSTRAINT users_created_key UNIQUE (created_at));
    CREATE INDEX ix_users_email ON sd_dst.users (email);
    CREATE TABLE sd_dst.orders (id int IDENTITY(1,1) PRIMARY KEY, user_id int NOT NULL, total decimal(10,2), note nvarchar(max),
      CONSTRAINT old_fk FOREIGN KEY (user_id) REFERENCES sd_dst.users (id));
    CREATE TABLE sd_dst.old_stuff (id int PRIMARY KEY);`);
  const select: Select = async (text, params) => {
    const request = pool.request();
    params.forEach((value, index) => request.input(`P${index + 1}`, mssql.NVarChar, value));
    return (await request.query(text)).recordset;
  };
  const side = (schema: string): Side => ({ select, exec: batch, database: null, schema });
  return {
    dialect: 'sqlserver',
    src: side('sd_src'),
    dst: side('sd_dst'),
    expectedKinds: ALL_KINDS,
    close: async () => {
      await batch(cleanup);
      await pool.close();
    }
  };
}

async function snapshot(item: Case, side: Side): Promise<SchemaSnapshot> {
  const { er, metadata } = queries[item.dialect];
  const tables = await listTables(side.select, er, side.database);
  return loadSchemaSnapshot({ select: side.select, metadata, dialect: item.dialect, tables, schema: side.schema });
}

const describe = (difference: SchemaDifference) => {
  const table = difference.table.source?.name ?? difference.table.target?.name;
  const subject = 'column' in difference ? difference.column.name
    : 'index' in difference ? difference.index.name
      : 'foreignKey' in difference ? difference.foreignKey.name
        : 'changes' in difference ? `${difference.target.name} (${difference.changes.join(', ')})` : '';
  return `${difference.kind} ${table}${subject ? `.${subject}` : ''}`;
};

async function roundTrip(item: Case): Promise<boolean> {
  const first: SchemaDiff = diffSchemas(await snapshot(item, item.src), await snapshot(item, item.dst));
  const kinds = new Set(first.differences.map((difference) => difference.kind));
  const missing = item.expectedKinds.filter((kind) => !kinds.has(kind));
  if (missing.length > 0) {
    console.log(`FAIL  ${item.dialect}: the fixture does not produce ${missing.join(', ')}`);
    first.differences.forEach((difference) => console.log(`        ${describe(difference)}`));
    return false;
  }
  const selected = new Set(first.differences.flatMap((difference, index) =>
    isSyncable(difference) && difference.kind !== skipKind ? [index] : []));
  const { metadata } = queries[item.dialect];
  const nativeDdl = await readNativeDdl({ select: item.src.select, metadata, dialect: item.dialect, diff: first, t });
  const plan = buildSyncScript(first, selected, { dialect: item.dialect, serverVersion: null, nativeDdl, t });
  if (plan.refusals.length > 0) {
    console.log(`FAIL  ${item.dialect}: refused ${plan.refusals.map((refusal) => `${refusal.table}.${refusal.subject} ${refusal.reason}`).join('; ')}`);
    return false;
  }
  for (const statement of plan.statements) {
    try {
      await item.dst.exec(statement);
    } catch (error) {
      console.log(`FAIL  ${item.dialect}: ${statement}\n        ${error instanceof Error ? error.message : String(error)}`);
      console.log(renderSyncScript(plan.statements));
      return false;
    }
  }
  const second = diffSchemas(await snapshot(item, item.src), await snapshot(item, item.dst));
  if (second.differences.length > 0) {
    console.log(`FAIL  ${item.dialect}: ${second.differences.length} difference(s) left after running the script`);
    second.differences.forEach((difference) => console.log(`        ${describe(difference)}`));
    console.log(renderSyncScript(plan.statements));
    return false;
  }
  console.log(`ok    ${item.dialect}: ${first.differences.length} differences, ${plan.statements.length} statements, none left`);
  return true;
}

const cases: Array<() => Case | Promise<Case>> = [sqliteCase];
const env = (name: string) => process.env[name]?.trim() || null;
const pg = env('DATAOMNI_POSTGRES_TEST_URL');
const my = env('DATAOMNI_MYSQL_TEST_URL');
const ms = env('DATAOMNI_SQLSERVER_TEST_URL');
if (pg) cases.push(() => postgresCase(pg)); else console.log('skip  postgresql (DATAOMNI_POSTGRES_TEST_URL not set)');
if (my) cases.push(() => mysqlCase(my)); else console.log('skip  mysql (DATAOMNI_MYSQL_TEST_URL not set)');
if (ms) cases.push(() => sqlServerCase(ms)); else console.log('skip  sqlserver (DATAOMNI_SQLSERVER_TEST_URL not set)');

let failed = false;
for (const make of cases) {
  const item = await make();
  try {
    if (!(await roundTrip(item))) failed = true;
  } finally {
    await item.close();
  }
}
process.exit(failed ? 1 : 0);
